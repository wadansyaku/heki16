import {promises as fs} from 'node:fs';
import net from 'node:net';
import dns from 'node:dns/promises';
const checks = [];
const check = (id, passed) => checks.push({id, passed});
check('nonroot', process.getuid() !== 0);
const deniedWrite = async file => { try { await fs.writeFile(file, 'synthetic-isolation-probe'); return false; } catch (e) { return ['EROFS','EACCES','EPERM'].includes(e.code); } };
check('root-readonly', await deniedWrite('/etc/nocturne-probe'));
check('tests-readonly', await deniedWrite('/project/tests/nocturne-probe.txt'));
check('harness-readonly', await deniedWrite('/trusted/tools/improvement/nocturne-probe.txt'));
check('dependencies-readonly', await deniedWrite('/opt/nocturne/node_modules/nocturne-probe.txt'));
check('no-host-home', !(await fs.stat('/Users/Yodai/.ssh').catch(() => null)));
check('no-docker-socket', !(await fs.stat('/var/run/docker.sock').catch(() => null)));
check('no-host-secrets', !Object.keys(process.env).some(k => /ANTHROPIC|CLOUDFLARE|OPENAI|AWS_|SSH_AUTH_SOCK|X_BEARER|GROK_API/.test(k)));
const connect = (host, port) => new Promise(resolve => { const c = net.connect({host, port}); c.setTimeout(500); const finish = value => { c.destroy(); resolve(value); }; c.on('connect', () => finish(true)); c.on('error', () => finish(false)); c.on('timeout', () => finish(false)); });
check('no-public-egress', !await connect('1.1.1.1', 443));
check('no-metadata-egress', !await connect('169.254.169.254', 80));
check('no-host-gateway', !await connect('192.168.5.2', 22));
check('no-ipv6-egress', !await connect('2606:4700:4700::1111', 443));
check('no-dns-egress', !await Promise.race([dns.lookup('example.com').then(() => true, () => false), new Promise(r => setTimeout(() => r(false), 1000))]));
console.log(JSON.stringify({passed: checks.every(c => c.passed), checks}));
process.exit(checks.every(c => c.passed) ? 0 : 2);
